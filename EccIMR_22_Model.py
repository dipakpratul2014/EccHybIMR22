def Dominant_Model(m, q0, e0, l0, fmin, angle, d, delta_t):
    """
    Hybrid PN+EOB model.
    Convention throughout:
        h22_complex = hp - i*hc
        hp =  real(sph22*h22 + sph2_2*h2_2)
        hc = -imag(sph22*h22 + sph2_2*h2_2)
    Ylm applied ONCE at the very end.
    """
    M   = m
    q   = q0
    M1  = q * M / (1 + q)
    M2  = M / (1 + q)
    eta = q / (1 + q)**2

    sph22, sph2_2 = sph_harmonics(angle, 2)

    # ── 1. Eccentric PN inspiral (raw modes, no Ylm) ──────────────────────────
    h22_insp, h2_2_insp, tinsp = INSP_Eber22(M, q0, e0, l0, fmin, angle, d, delta_t)

    # ── 2. Circular EOB (inclination=0 → raw modes, Ylm applied manually) ────
    wfm_gen = GenerateWaveform({
        "mass1": M1, "mass2": M2,
        "spin1x": 0, "spin1y": 0, "spin1z": 0,
        "spin2x": 0, "spin2y": 0, "spin2z": 0,
        "deltaT": delta_t, "f22_start": fmin,
        "distance": d, "inclination": 0,        # raw modes, Ylm done below
        "approximant": "SEOBNRv5HM"
    })
    times_eob, hlm_eob = wfm_gen.generate_td_modes()
    t_peak    = times_eob[np.argmax(np.abs(hlm_eob[(2, 2)]))]
    times_eob = times_eob - t_peak

    h22_eob  = hlm_eob[(2,  2)]
    h2_2_eob = hlm_eob[(2, -2)]           # use LAL mode directly

    # ── 3. Time shift ─────────────────────────────────────────────────────────
    tshift = -tshift_qel(q0, e0, l0) * M * MTSUN_SI
    tmin   = max([tinsp[0] - tshift, times_eob[0]])

    # ── 4. Interpolate EOB onto common grid ───────────────────────────────────
    re_eob_p = interp1d(times_eob, np.real(h22_eob),  kind='cubic', fill_value='extrapolate')
    im_eob_p = interp1d(times_eob, np.imag(h22_eob),  kind='cubic', fill_value='extrapolate')
    re_eob_m = interp1d(times_eob, np.real(h2_2_eob), kind='cubic', fill_value='extrapolate')
    im_eob_m = interp1d(times_eob, np.imag(h2_2_eob), kind='cubic', fill_value='extrapolate')

    tImr     = np.arange(tmin, times_eob[-1], delta_t)
    h22_Imr  = re_eob_p(tImr) + 1j * im_eob_p(tImr)
    h2_2_Imr = re_eob_m(tImr) + 1j * im_eob_m(tImr)

    # ── 5. Interpolate PN inspiral onto common grid ───────────────────────────
    re_insp = interp1d(tinsp - tshift, np.real(h22_insp), kind='cubic', fill_value='extrapolate')
    im_insp = interp1d(tinsp - tshift, np.imag(h22_insp), kind='cubic', fill_value='extrapolate')

    tEcc     = np.arange(tmin, tinsp[-1] - tshift, delta_t)
    h22_Ecc  = re_insp(tEcc) + 1j * im_insp(tEcc)
    h2_2_Ecc = np.conj(h22_Ecc)

    # ── 6. Phase alignment ────────────────────────────────────────────────────
    phaseEcc = np.unwrap(np.angle(h22_Ecc) * 2) / 2    # NO abs()
    phaseImr = np.unwrap(np.angle(h22_Imr) * 2) / 2    # NO abs()

    dphase   = phaseEcc[0] - phaseImr[0]
    h22_Ecc  = h22_Ecc * np.exp(-1j * dphase)
    h2_2_Ecc = np.conj(h22_Ecc)                         # keep symmetry
    phaseEcc = np.unwrap(np.angle(h22_Ecc) * 2) / 2

    # ── 7. Amplitude blending ─────────────────────────────────────────────────
    tval_amp = tamp_qel(q0, e0, l0)
    if tval_amp > -30 or tval_amp < (tmin / (2.0 * M * MTSUN_SI)):
        tmatch_amp = -1000 if q0 <= 3 else tmin / (2.0 * M * MTSUN_SI)
    else:
        tmatch_amp = tval_amp

    Idxjoin = np.argmin(np.abs(tEcc - tmatch_amp * M * MTSUN_SI))
    tstop   = -30 * M * MTSUN_SI
    lst     = np.argmin(np.abs(tEcc - tstop))
    indx    = lst - Idxjoin
    n       = indx - 1

    amp_blend = [
        ((n - k) * np.abs(h22_Ecc[Idxjoin + k]) + k * np.abs(h22_Imr[Idxjoin + k])) / n
        for k in range(indx)
    ]

    amp_model = np.concatenate([
        np.abs(h22_Ecc[:Idxjoin]),
        amp_blend,
        np.abs(h22_Imr[Idxjoin + indx:])
    ])

    t_model = np.concatenate([
        tEcc[:Idxjoin + indx],
        tImr[Idxjoin + indx:]
    ])

    # ── 8. Frequency blending ─────────────────────────────────────────────────
    omegaEcc = (M * MTSUN_SI / delta_t) * np.gradient(phaseEcc)
    omegaImr = (M * MTSUN_SI / delta_t) * np.gradient(phaseImr)

    tval_freq = tfreq_qel(q0, e0, l0)
    if tval_freq > -30 or tval_freq < (tmin / (2.0 * M * MTSUN_SI)):
        tjoin0 = -500
    else:
        tjoin0 = tval_freq

    tjoin = tjoin0 * M * MTSUN_SI
    fjoin = np.argmin(np.abs(tEcc - tjoin))
    tstop = min([tEcc[-1], -30 * M * MTSUN_SI])
    lst   = np.argmin(np.abs(tEcc - tstop))
    indx  = lst - fjoin
    n     = indx - 1

    freq_blend = [
        ((n - k) * omegaEcc[fjoin + k] + k * omegaImr[fjoin + k]) / n
        for k in range(indx)
    ]

    freq_model = np.concatenate([
        omegaEcc[:fjoin],
        freq_blend,
        omegaImr[fjoin + indx:]
    ])

    # ── 9. Reconstruct phase from blended frequency ───────────────────────────
    phase_model = np.cumsum(freq_model) / (M * MTSUN_SI / delta_t)
    phase_model = phase_model - phase_model[0] + phaseEcc[0]

    # ── 10. Build hybrid h22 MODE (no Ylm yet) ────────────────────────────────
    ll          = min([len(amp_model), len(phase_model)])
    h22_hybrid  = amp_model[:ll] * np.exp(1j * phase_model[:ll])
    h2_2_hybrid = np.conj(h22_hybrid)

    # ── 11. Apply Ylm ONCE here to get physical strain ────────────────────────
    ht     = sph22 * h22_hybrid + sph2_2 * h2_2_hybrid
    hplus  =  np.real(ht)
    hcross = -np.imag(ht)

    hp_model_TS = TimeSeries(hplus,  delta_t)
    hc_model_TS = TimeSeries(hcross, delta_t)

    return hp_model_TS, hc_model_TS, t_model




