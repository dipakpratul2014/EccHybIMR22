def INSP_Eber22(M0, q, e0, l0, flow, inc, d0, delta_t):
    """
    Returns raw h22, h2_2 modes + time vector (NO Ylm applied).
    Convention: h22  = A * exp(-i*m*psi/2)
                h2_2 = conj(h22)
    """
    eta = neu = nu = q / (1 + q)**2
    G = c = M = d = 1
    M2 = M / (1 + q)
    M1 = M2 * q
    Delta = math.sqrt(1 - 4*neu)
    gamma = EulerGamma = 0.577215664901

    xlow  = (M0 * MTSUN_SI * math.pi * flow) ** (2/3)
    f_low = xlow**(3/2) / (M * MTSUN_SI * math.pi)

    x   = xlow
    v   = math.sqrt(x)
    xie = v**3

    if delta_t >= 1/2**14:
        del_t = 1/2**14
    elif delta_t >= 1/2**16:
        del_t = 1/2**16
    elif delta_t >= 1/2**18:
        del_t = 1/2**18
    else:
        del_t = 1/2**20

    phase_EccTD, tVec_PN = PNparams(M, q, d, f_low, e0, del_t)

    tC_NR  = 0
    x0     = xlow
    xi0    = x0**(3/2)
    v0     = xi0**(1/3)
    theta  = ((5*M/eta)**(1/8)) * (tC_NR - tVec_PN)**(-1/8)
    theta0 = ((5*M/eta)**(1/8)) * (tC_NR - tVec_PN[0])**(-1/8)

    fVec     = x_from_t(theta, theta0, e0, M, eta)
    plotIdx2 = np.nonzero(fVec >= 0)
    fVec     = fVec[plotIdx2]
    xiVec    = np.pi * M * fVec
    xVec     = xiVec**(2/3)
    xband    = np.where(xVec <= 1/6)
    xVec     = xVec[xband]
    maxPNidx = len(xVec)
    tVec_PN  = tVec_PN[:maxPNidx]

    lp = mp = 2

    xVec = np.array(xVec)
    v    = np.sqrt(xVec)
    v0   = math.sqrt(x0)
    xie  = v**3
    xi0  = v0**3

    l   = mean_anomaly(xie, xi0, l0, eta, e0)
    e   = e0 * (xi0/xie)**(19/18) * epsilon(xie, eta) / epsilon(xi0, eta)
    psi = np.array(phase_EccTD)[:len(xVec)]
    xi  = l

    h    = amplitude_22(xi, xVec, nu, Delta, e)

    # ── mode convention: h22 = A*exp(-i*m*psi/2), h2_2 = conj(h22) ──────────
    h22  = 8*np.sqrt(np.pi/5) * M * neu * xVec * h * np.exp(-1j * mp * psi / 2) / d
    h2_2 = np.conj(h22)
    # ─────────────────────────────────────────────────────────────────────────

    conv_h = G_SI * M0 * MSUN_SI / (10**6 * PC_SI * d0) / C_SI**2
    conv_t = M0 * MTSUN_SI

    h22  = h22  * conv_h
    h2_2 = h2_2 * conv_h

    time  = tVec_PN * conv_t
    time  = time - time[-1]          # t=0 at end of inspiral

    t_out = np.arange(time[0], time[-1], delta_t)
    re22_i = interp1d(time, np.real(h22),  kind='cubic', fill_value='extrapolate')
    im22_i = interp1d(time, np.imag(h22),  kind='cubic', fill_value='extrapolate')
    h22_out  = re22_i(t_out) + 1j * im22_i(t_out)
    h2_2_out = np.conj(h22_out)

    # ── return raw modes, NO Ylm ──────────────────────────────────────────────
    return h22_out, h2_2_out, t_out


